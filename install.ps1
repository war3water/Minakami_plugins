# One-command install for Minakami Plugins (Windows PowerShell 5.1 or PowerShell 7 on any OS).
# Installs every plugin into each agent runtime on PATH: Claude Code, Codex CLI, Grok Build, and pi.
# Re-running it brings everything to the latest version.
# Set $env:MINAKAMI_RUNTIMES to a comma-separated subset (claude,codex,grok,pi) to install into only those.
# Safe under both `.\install.ps1` and `iwr ... | iex`: it never calls `exit`, and returns instead.
$ErrorActionPreference = 'Continue'

$Marketplace = 'war3water/Minakami_plugins'
$MarketplaceName = 'minakami-plugins'
$PiSource = 'git:github.com/war3water/Minakami_plugins'

# >>> generated by scripts/sync-manifests.sh from .agents/plugins/marketplace.json; do not edit
$Plugins = @('agent-coord-bootstrap', 'prompt-audit', 'code-map', 'code-cleanup')
$Skills = @('agent-coord-bootstrap:check-templates', 'agent-coord-bootstrap:init-agent-coord', 'agent-coord-bootstrap:review-readme', 'prompt-audit:audit-prompt', 'prompt-audit:check-sources', 'code-map:code-map', 'code-cleanup:code-cleanup')
# <<< generated

Write-Host 'Minakami Plugins installer'
Write-Host "  marketplace: $Marketplace"

$Found = @()
$Failures = @()

# The runtime's executable, or $null when it is left out by MINAKAMI_RUNTIMES or not on PATH. It looks up
# applications only (.exe, .cmd), never npm's .ps1 shims, which the default execution policy refuses to run.
function Get-Runtime([string]$Name, [string]$Label) {
    Write-Host ''
    if ($env:MINAKAMI_RUNTIMES) {
        $wanted = @($env:MINAKAMI_RUNTIMES -split '[,\s]+' | Where-Object { $_ })
        if ($wanted -notcontains $Name) {
            Write-Host "[$Name] left out by MINAKAMI_RUNTIMES"
            return $null
        }
    }
    $cmd = Get-Command $Name -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $cmd) {
        Write-Host "[$Name] $Label not found on PATH - skipping"
        return $null
    }
    Write-Host "[$Name] $Label"
    return $cmd.Source
}

$claude = Get-Runtime 'claude' 'Claude Code'
if ($claude) {
    $Found += 'claude'
    # add succeeds on an already-registered marketplace without refreshing it, so always refresh;
    # the refresh also fails when add did not register it, which is the failure that matters
    & $claude plugin marketplace add $Marketplace
    & $claude plugin marketplace update $MarketplaceName
    if ($LASTEXITCODE -ne 0) { $Failures += 'claude: marketplace add/update failed' }
    foreach ($p in $Plugins) {
        Write-Host "[claude] installing $p"
        & $claude plugin install "$p@$MarketplaceName"
        if ($LASTEXITCODE -ne 0) { $Failures += "claude: install $p failed"; continue }
        # install leaves an already-installed plugin at its installed version; update brings it current
        & $claude plugin update "$p@$MarketplaceName"
        if ($LASTEXITCODE -ne 0) { $Failures += "claude: update $p failed" }
    }
}

$codex = Get-Runtime 'codex' 'Codex CLI'
if ($codex) {
    $Found += 'codex'
    # same as above: add leaves an existing snapshot stale, so always upgrade it
    & $codex plugin marketplace add $Marketplace
    & $codex plugin marketplace upgrade $MarketplaceName
    if ($LASTEXITCODE -ne 0) { $Failures += 'codex: marketplace add/upgrade failed' }
    foreach ($p in $Plugins) {
        Write-Host "[codex] installing $p"
        & $codex plugin add "$p@$MarketplaceName"
        if ($LASTEXITCODE -ne 0) { $Failures += "codex: add $p failed" }
    }
}

$grok = Get-Runtime 'grok' 'Grok Build'
if ($grok) {
    $Found += 'grok'
    # Grok also loads the plugins installed in Claude Code (its Claude compatibility, on by default).
    # Install a plugin into Grok only when Grok doesn't already load it from there, so that no skill
    # is loaded twice. When Grok can't report what it loads, install nothing rather than risk duplicates.
    $seen = $null
    $raw = & $grok inspect --json 2>$null | Out-String
    if ($LASTEXITCODE -eq 0) {
        try { $seen = $raw | ConvertFrom-Json } catch { $seen = $null }
    }
    if (-not $seen) {
        $Failures += "grok: 'grok inspect --json' failed, so it's unknown which plugins Grok already loads; nothing was installed into Grok"
    } else {
        $fromClaude = @($seen.plugins | Where-Object {
            $_.path -match 'claude' -and $_.path -match [regex]::Escape($MarketplaceName)
        } | ForEach-Object { $_.name })
        $listed = (& $grok plugin list 2>$null | Out-String)
        foreach ($p in $Plugins) {
            if ($fromClaude -contains $p) {
                Write-Host "[grok] ${p}: loaded from Claude Code"
            } elseif ($listed -match (': ' + [regex]::Escape($p) + ' \[')) {
                Write-Host "[grok] updating $p"
                & $grok plugin update $p
                if ($LASTEXITCODE -ne 0) { $Failures += "grok: update $p failed" }
            } else {
                Write-Host "[grok] installing $p"
                & $grok plugin install "$Marketplace#$p" --trust
                if ($LASTEXITCODE -ne 0) { $Failures += "grok: install $p failed" }
            }
        }
    }
}

$pi = Get-Runtime 'pi' 'pi'
if ($pi) {
    $Found += 'pi'
    # pi installs the whole repository as one package; its package.json points pi at every plugin's skills
    $listed = (& $pi list 2>$null | Out-String)
    if ($listed -match 'github\.com/war3water/Minakami_plugins') {
        Write-Host "[pi] updating the $MarketplaceName package"
        & $pi update $PiSource
        if ($LASTEXITCODE -ne 0) { $Failures += 'pi: update failed' }
    } else {
        Write-Host "[pi] installing the $MarketplaceName package"
        & $pi install $PiSource
        if ($LASTEXITCODE -ne 0) { $Failures += 'pi: install failed' }
    }
}

if ($Found.Count -eq 0) {
    Write-Host ''
    Write-Host 'No runtime to install into: none of claude, codex, grok, or pi was found on PATH,'
    Write-Host 'or MINAKAMI_RUNTIMES left them out. Install at least one and re-run this script.'
    $global:LASTEXITCODE = 1
    return
}

# Personal skill folders with a plugin skill's name shadow the plugin or load next to it.
$skillDirs = @(
    $(if ($env:CLAUDE_CONFIG_DIR) { Join-Path $env:CLAUDE_CONFIG_DIR 'skills' } else { Join-Path $HOME '.claude/skills' }),
    $(if ($env:CODEX_HOME) { Join-Path $env:CODEX_HOME 'skills' } else { Join-Path $HOME '.codex/skills' }),
    (Join-Path $HOME '.agents/skills'),
    (Join-Path $HOME '.grok/skills'),
    $(if ($env:PI_CODING_AGENT_DIR) { Join-Path $env:PI_CODING_AGENT_DIR 'skills' } else { Join-Path $HOME '.pi/agent/skills' })
)
$stale = @()
foreach ($entry in $Skills) {
    $s = $entry.Split(':')[1]
    foreach ($d in $skillDirs) {
        $path = Join-Path $d $s
        if (Test-Path -LiteralPath $path) { $stale += $path }
    }
}
if ($stale.Count -gt 0) {
    Write-Host ''
    Write-Host 'WARNING: these personal skill folders have the same name as a plugin skill, so a runtime may load'
    Write-Host 'them instead of the plugin, or both. Remove them unless you keep them on purpose:'
    foreach ($s in $stale) { Write-Host "  - $s" }
}

if ($Failures.Count -gt 0) {
    Write-Host ''
    Write-Host 'FAILED steps:'
    foreach ($f in $Failures) { Write-Host "  - $f" }
    $global:LASTEXITCODE = 1
    return
}

Write-Host ''
Write-Host 'Done. Restart any running agent session to load the new versions.'
Write-Host 'Start a skill with:'
foreach ($r in $Found) {
    switch ($r) {
        'claude' { Write-Host '  Claude Code: /<plugin>:<skill>, e.g. /code-cleanup:code-cleanup' }
        'codex' { Write-Host '  Codex CLI:   type $ and pick the skill, e.g. $code-cleanup (interactive sessions only)' }
        'grok' { Write-Host '  Grok Build:  /<skill>, or /<plugin>:<skill> when two skills share a name' }
        'pi' { Write-Host '  pi:          /skill:<skill>, e.g. /skill:code-cleanup' }
    }
}
Write-Host 'Skills in each plugin:'
foreach ($p in $Plugins) {
    $names = @($Skills | Where-Object { $_.Split(':')[0] -eq $p } | ForEach-Object { $_.Split(':')[1] })
    Write-Host "  ${p}: $($names -join ', ')"
}
$global:LASTEXITCODE = 0
