#!/usr/bin/env bash
# Sync everything derived from the canonical manifests, then verify it. Run before committing a plugin or
# manifest change:
#   1. copy each plugin's .codex-plugin/plugin.json over its .claude-plugin/plugin.json, and the canonical
#      .agents/plugins/marketplace.json over .claude-plugin/marketplace.json;
#   2. rewrite the generated plugin and skill lists in install.sh and install.ps1;
#   3. fail when a plugin folder isn't registered in the marketplace, or a registered one is missing.
set -euo pipefail

cd "$(dirname "$0")/.."

MARKETPLACE=.agents/plugins/marketplace.json

# Plugin names in marketplace order. Each entry's source path is its folder, and the folder name is the
# plugin name (checked below).
PLUGINS=()
while IFS= read -r p; do
  PLUGINS+=("$p")
done < <(grep -o '"path": *"[^"]*"' "$MARKETPLACE" | sed 's/.*"\([^"]*\)"$/\1/')
[ "${#PLUGINS[@]}" -gt 0 ] || { echo "No plugins found in $MARKETPLACE" >&2; exit 1; }

for p in "${PLUGINS[@]}"; do
  [ -f "$p/.codex-plugin/plugin.json" ] || { echo "$p: registered, but $p/.codex-plugin/plugin.json is missing" >&2; exit 1; }
  grep -q "\"name\": *\"$p\"" "$p/.codex-plugin/plugin.json" || { echo "$p: plugin.json name differs from its folder" >&2; exit 1; }
done
for manifest in */.codex-plugin/plugin.json; do
  p=${manifest%%/*}
  printf '%s\n' "${PLUGINS[@]}" | grep -qx "$p" || { echo "$p: has a manifest but isn't in $MARKETPLACE" >&2; exit 1; }
done

# 1. Manifest mirrors.
for p in "${PLUGINS[@]}"; do
  mkdir -p "$p/.claude-plugin"
  cp "$p/.codex-plugin/plugin.json" "$p/.claude-plugin/plugin.json"
done
cp "$MARKETPLACE" .claude-plugin/marketplace.json

# 2. Installer lists: the plugins, and each plugin's skills as plugin:skill.
SKILLS=()
for p in "${PLUGINS[@]}"; do
  for f in "$p"/skills/*/SKILL.md; do
    [ -f "$f" ] || continue
    s=${f%/SKILL.md}
    SKILLS+=("$p:${s##*/}")
  done
done

sh_list() { local out="" x; for x in "$@"; do out+=" \"$x\""; done; printf '(%s)' "${out# }"; }
ps_list() { local out="" x; for x in "$@"; do out+=", '$x'"; done; printf '@(%s)' "${out#, }"; }

replace_block() {  # replace_block FILE BODY: replace the lines between the generated markers with BODY
  local file=$1 body=$2 tmp
  grep -q '^# >>> generated by scripts/sync-manifests.sh' "$file" || { echo "$file: generated block not found" >&2; exit 1; }
  tmp=$(mktemp)
  BODY="$body" awk '
    /^# >>> generated by scripts\/sync-manifests.sh/ { print; print ENVIRON["BODY"]; skip = 1; next }
    /^# <<< generated/ { skip = 0 }
    !skip { print }
  ' "$file" | tr -d '\r' > "$tmp"
  # keep the file's line endings: Git for Windows checks the installers out with CRLF
  if grep -q $'\r' "$file"; then
    awk '{ printf "%s\r\n", $0 }' "$tmp" > "$file"
  else
    cat "$tmp" > "$file"
  fi
  rm -f "$tmp"
}

replace_block install.sh "PLUGINS=$(sh_list "${PLUGINS[@]}")
SKILLS=$(sh_list "${SKILLS[@]}")"
replace_block install.ps1 "\$Plugins = $(ps_list "${PLUGINS[@]}")
\$Skills = $(ps_list "${SKILLS[@]}")"

# 3. Verify.
for p in "${PLUGINS[@]}"; do
  diff "$p/.codex-plugin/plugin.json" "$p/.claude-plugin/plugin.json"
done
diff "$MARKETPLACE" .claude-plugin/marketplace.json
bash -n install.sh

echo "Manifest pairs are in sync; the installers list ${#PLUGINS[@]} plugins and ${#SKILLS[@]} skills."
